class Status:
    """The part of MediaWiki's Status the extension uses: a value and warnings (message key, params...)."""

    def __init__(self):
        self.value: Any = None
        self.warnings: list[tuple] = []

    def warning(self, key: str, *params) -> None:
        self.warnings.append((key, *params))

    def is_good(self) -> bool:
        return not self.warnings

    def is_ok(self) -> bool:
        return True

    def get_value(self):
        return self.value


_ASCII_LOWER = str.maketrans("ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz")


def _php_trim(s: str) -> str:
    return s.strip(" \t\n\r\0\x0b")


def _ctype_digit(value) -> bool:
    return isinstance(value, str) and value != "" and value.isascii() and value.isdigit()


def _ctype_alpha(value) -> bool:
    return isinstance(value, str) and value != "" and value.isascii() and value.isalpha()


def _php_intval(value: str) -> int:
    """PHP intval() of a string: leading whitespace, an optional sign and the digits that follow; else 0."""
    m = re.match(r"[ \t\n\r\x0b\f]*([+-]?\d+)", value)
    return int(m.group(1)) if m else 0


def _htmlspecialchars_noquotes(text: str) -> str:
    """htmlspecialchars( $text, ENT_NOQUOTES )"""
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def get_lexer(lang: Optional[str]) -> Optional[str]:
    """Get the Pygments lexer name for a particular language; None if no matching lexer."""
    if lang is None:
        return None

    lexer = lang.translate(_ASCII_LOWER)  # strtolower()

    if lexer in LEXERS:
        return lexer

    # Check if this is a GeSHi lexer name for which there exists a compatible Pygments lexer with a different name.
    if lexer in COMPATIBLE_LEXERS:
        # PHP: if ( in_array( $lexer, $lexers ) ) return $lexer; - $lexers maps names to true, and a non-empty
        # string loosely equals true, so the mapped name is always taken
        return COMPATIBLE_LEXERS[lexer]

    return None


def register(parser) -> None:
    """ParserFirstCallInit: register parser hook"""
    parser.set_hook("source", parser_hook_source)
    parser.set_hook("syntaxhighlight", parser_hook)


def parser_hook_source(text: Optional[str], args: dict, parser, frame=None) -> str:
    """Parser hook for <source> to add deprecated tracking category"""
    parser.add_tracking_category("syntaxhighlight-source-category")
    return parser_hook(text, args, parser, frame)


def process_content(text: str, args: dict, parser=None) -> dict:
    """{'html': ..., 'cats': [message keys of the tracking categories]}"""
    # Don't trim leading spaces away, just the linefeeds
    out = re.sub(r"^\n+", "", text.rstrip(" \t\n\r\0\x0b"))
    tracking_cats = []

    args = dict(args)
    # Convert deprecated attributes
    if "enclose" in args:
        if args["enclose"] == "none":
            args["inline"] = True
        del args["enclose"]
        tracking_cats.append("syntaxhighlight-enclose-category")

    lexer = args.get("lang", "")
    if lexer is None:
        lexer = ""

    result = highlight(out, lexer, args, parser)
    if not result.is_good():
        tracking_cats.append("syntaxhighlight-error-category")

    return {"html": result.get_value(), "cats": tracking_cats}


def parser_hook(text: Optional[str], args: dict, parser, frame=None) -> str:
    """Parser hook for both <source> and <syntaxhighlight> logic"""
    # Replace strip markers (For e.g. {{#tag:syntaxhighlight|<nowiki>...}})
    out = parser.get_strip_state().unstrip_no_wiki(text or "")

    result = process_content(out, args, parser)
    for cat in result["cats"]:
        parser.add_tracking_category(cat)

    # Register CSS: $parser->getOutput()->addModuleStyles( [ 'ext.pygments' ] ) - no ResourceLoader here

    return result["html"]


def unwrap(out: str) -> str:
    """Unwrap the <div> wrapper of the Pygments output"""
    if out != "":
        m = re.match(r'<div class="?mw-highlight"?>(.*)</div>\Z', _php_trim(out), re.S)
        if m:
            out = _php_trim(m.group(1))
        else:
            raise MWException("Unexpected output from Pygments encountered")
    return out


def plain_code_wrap(code: str, is_inline: bool) -> str:
    """HTML of the code without syntax highlighting."""
    if is_inline:
        return _htmlspecialchars_noquotes(code)

    return raw_element("div", {"class": HIGHLIGHT_CSS_CLASS}, element("pre", {}, code))


def highlight_inner(code: str, lang: Optional[str] = None, args: Optional[dict] = None) -> Status:
    args = args or {}
    status = Status()

    lexer = get_lexer(lang)
    if lexer is None and lang is not None:
        status.warning("syntaxhighlight-error-unknown-language", lang)

    # For empty tag, output nothing instead of empty <pre>.
    if code == "":
        status.value = ""
        return status

    length = len(code.encode("utf-8"))  # strlen() counts bytes
    if length > HIGHLIGHT_MAX_BYTES:
        # Disable syntax highlighting
        lexer = None
        status.warning("syntaxhighlight-error-exceeds-size-limit", length, HIGHLIGHT_MAX_BYTES)

    is_inline = "inline" in args
    show_lines = "line" in args

    if is_inline:
        code = _php_trim(code)

    if lexer is None:
        # When syntax highlighting is disabled..
        status.value = plain_code_wrap(code, is_inline)
        return status

    options: dict[str, Any] = {
        "cssclass": HIGHLIGHT_CSS_CLASS,
        "encoding": "utf-8",
    }

    # Line numbers
    if show_lines:
        options["linenos"] = "inline"

    if lexer == "php" and "<?php" not in code:
        options["startinline"] = 1

    # Highlight specific lines
    if "highlight" in args:
        lines = parse_highlight_lines(args["highlight"])
        if lines:
            options["hl_lines"] = " ".join(str(n) for n in lines)

    # Starting line number
    if "start" in args and _ctype_digit(args["start"]):
        options["linenostart"] = int(args["start"])

    if args.get("linelinks") and _ctype_alpha(args["linelinks"]):
        options["linespans"] = args["linelinks"]

    if is_inline:
        options["nowrap"] = 1

    # (WANObjectCache::getWithSetCallback() around the Pygments invocation; no cache here, it cannot fail)
    status.value = Pygmentize.highlight(lexer, code, options)

    return status


def _php_replacement(template: str, m: re.Match) -> str:
    """A preg_replace() replacement string for one match: $n, ${n} and \\n are the groups."""
    def group(g: re.Match) -> str:
        n = int(g.group(1) or g.group(2) or g.group(3))
        return (m.group(n) or "") if n <= (m.re.groups or 0) else ""

    return re.sub(r"\$(\d{1,2})|\$\{(\d{1,2})\}|\\(\d{1,2})", group, template)


# '`<span class="linenos">\s*([^<]*)\s*</span>`' (PCRE \s without /u: ASCII whitespace)
_LINENOS = re.compile(r'<span class="linenos">[ \t\n\x0b\f\r]*([^<]*)[ \t\n\x0b\f\r]*</span>')


def highlight(code: str, lang: Optional[str] = None, args: Optional[dict] = None, parser=None) -> Status:
    """Highlight a code-block using a particular lexer.

    This produces raw HTML (wrapped by Status), the caller is responsible for making sure the "ext.pygments" module
    is loaded in the output.

    ``args``: if it contains a 'line' key, the output will include line numbers. If it includes a 'highlight' key,
    the value will be parsed as a comma-separated list of lines and line-ranges to highlight. If it contains a
    'start' key, the value will be used as the line at which to start highlighting. If it contains a 'inline' key,
    the output will not be wrapped in `<div><pre/></div>`. If it contains a 'linelinks' key, lines will have links
    and anchors with a prefix of the value. Similar to the lineanchors+linespans features in Pygments.
    ``parser``: Parser, if generating content to be parsed. Returns a Status object, with HTML representing the
    highlighted code as its value."""
    args = args or {}
    status = highlight_inner(code, lang, args)
    output = status.get_value()

    is_inline = "inline" in args
    show_lines = "line" in args
    lexer = get_lexer(lang)

    # Post-Pygment HTML transformations.

    if show_lines:
        line_replace = element("span", {"class": "linenos", "data-line": "$1"})
        if args.get("linelinks"):
            line_replace = raw_element("a", {"href": "#" + str(args["linelinks"]) + "-$1"}, line_replace)
        # Convert line numbers to data attributes so they can be displayed as CSS generated content and be
        # unselectable in all browsers.
        output = _LINENOS.sub(lambda m: _php_replacement(line_replace, m), output)

    # Allow certain HTML attributes
    config = parser.config if parser is not None else DEFAULT
    html_attribs = validate_attributes({k: v for k, v in args.items() if isinstance(v, str)},
                                       {"style": True, "class": True, "id": True}, config=config)

    dir_ = "rtl" if args.get("dir") == "rtl" else "ltr"

    # Build class list
    class_list = []
    if "class" in html_attribs:
        class_list.append(html_attribs["class"])
    class_list.append(HIGHLIGHT_CSS_CLASS)
    if lexer is not None:
        class_list.append(HIGHLIGHT_CSS_CLASS + "-lang-" + lexer)
    class_list.append("mw-content-" + dir_)
    if show_lines:
        class_list.append(HIGHLIGHT_CSS_CLASS + "-lines")
    html_attribs["class"] = " ".join(class_list)
    html_attribs["dir"] = dir_

    if is_inline:
        # We've already trimmed the input $code before highlighting, but pygment's standard out adds a line break
        # afterwards, which would then be preserved in the paragraph that wraps this, and become visible as a
        # space. Avoid that.
        output = _php_trim(output)

        # Enforce inlineness. Stray newlines may result in unexpected list and paragraph processing (also known as
        # doBlockLevels()).
        output = output.replace("\n", " ")
        output = raw_element("code", html_attribs, output)
    else:
        output = unwrap(output)

        if parser is not None:
            # Use 'nowiki' strip marker to prevent list processing (also known as doBlockLevels()). However, leave
            # the wrapping <div/> outside to prevent <p/>-wrapping.
            marker = f"{MARKER_PREFIX}-syntaxhighlightinner-{parser.marker_index:08X}{MARKER_SUFFIX}"
            parser.marker_index += 1
            parser.get_strip_state().add_no_wiki(marker, output)
            output = marker

        output = open_element("div", html_attribs) + output + close_element("div")

    status.value = output
    return status


def parse_highlight_lines(line_spec: str) -> list[int]:
    """Take an input specifying a list of lines to highlight, returning a raw list of matching line numbers.

    Input is comma-separated list of lines or line ranges."""
    lines: list[int] = []
    values = [_php_trim(v) for v in str(line_spec).split(",")]
    for value in values:
        if _ctype_digit(value):
            lines.append(int(value))
        elif "-" in value:
            start, end = (_php_intval(v) for v in value.split("-")[:2])
            if valid_highlight_range(start, end):
                lines.extend(range(start, end + 1))
        if len(lines) > HIGHLIGHT_MAX_LINES:
            lines = lines[:HIGHLIGHT_MAX_LINES]
            break
    return lines


def valid_highlight_range(start: int, end: int) -> bool:
    """Validate a provided input range"""
    # Since we're taking this tiny range and producing a an array of every integer between them, it would be trivial
    # to DoS the system by asking for a huge range. Impose an arbitrary limit on the number of lines in a given range
    # to reduce the impact.
    return start > 0 and start < end and end - start < HIGHLIGHT_MAX_LINES


# Pygments' escape_html() table
_ESCAPE_HTML = str.maketrans({"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"})


class Pygmentize:
    """Stands in for the `pygmentize` command (Pygmentize::highlight())."""

    @staticmethod
    def highlight(lexer: str, code: str, options: dict) -> str:
        """``pygmentize -l <lexer> -f html -O <options> file``, with every lexer replaced by TextLexer: the code is
        one Token.Text, which HtmlFormatter writes without a span. The options handled are those the extension
        passes: cssclass, linenos=inline, linenostart, hl_lines, linespans, nowrap (encoding and PHP's startinline
        do not change the HTML)."""
        # Lexer.get_tokens(): the text is preprocessed (stripnl and ensurenl are on by default)
        text = code
        if text.startswith("﻿"):
            text = text[len("﻿"):]
        text = text.replace("\r\n", "\n")
        text = text.replace("\r", "\n")
        text = text.strip("\n")
        if not text.endswith("\n"):
            text += "\n"

        # HtmlFormatter.__init__()
        nowrap = str(options.get("nowrap", "")).lower() in ("1", "yes", "true", "on")
        linenos = 2 if options.get("linenos") == "inline" else 0
        linenostart = abs(int(options.get("linenostart", 1)))
        hl_lines = set()
        for lineno in str(options.get("hl_lines", "")).split():
            try:
                hl_lines.add(int(lineno))
            except ValueError:
                pass
        linespans = options.get("linespans", "")
        cssclass = options.get("cssclass", "highlight")

        # _format_lines(): a Token.Text has no CSS class, so each line is the escaped text and the line separator
        source = [part + "\n" for part in text.translate(_ESCAPE_HTML).split("\n")[:-1]]

        # As a special case, we wrap line numbers before line highlighting so the line numbers get wrapped in the
        # highlighting tag.
        if not nowrap and linenos == 2:
            # _wrap_inlinelinenos() (linenostep 1, no linenospecial, lineanchors or anchorlinenos)
            mw = len(str(len(source) + linenostart - 1))
            source = ['<span class="linenos">%*d</span>' % (mw, num) + line
                      for num, line in enumerate(source, linenostart)]

        if hl_lines:
            # _highlight_lines()
            source = ['<span class="hll">%s</span>' % line if i + 1 in hl_lines else line
                      for i, line in enumerate(source)]

        if nowrap:
            return "".join(source)

        if linespans:
            # _wrap_linespans()
            source = ['<span id="%s-%d">%s</span>' % (linespans, i, line)
                      for i, line in enumerate(source, linenostart)]
        # wrap(): _wrap_div( _wrap_pre( source ) ); the empty span here is to keep leading empty lines from being
        # ignored by HTML parsers
        return ("<div" + (cssclass and ' class="%s"' % cssclass) + ">" + "<pre><span></span>" + "".join(source)
                + "</pre>" + "</div>\n")
