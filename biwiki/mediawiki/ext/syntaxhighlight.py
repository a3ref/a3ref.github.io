"""The <syntaxhighlight> and <source> tags: code in <div class="mw-highlight ..."><pre>...</pre></div> (or <code> with
``inline``), with line numbers (``line``, ``start``, ``linelinks``), highlighted lines (``highlight``), ``class``,
``style``, ``id`` and ``dir``.

What differs from the HTML the wiki produces: only the token spans. For a language Pygments knows, the real output
wraps keywords, names, punctuation etc. in ``<span class="kd">``, ``<span class="nx">``, ...; here the code is a
single text token, as Pygments' own ``text`` lexer gives (so lang="text" is exact). Everything around it is the
same: the wrapper, its classes and attributes, ``<span></span>`` at the start of the <pre>, the final newline,
``<span class="linenos" data-line="N"></span>``, ``<span class="hll">``, ``<span id="L-N">``, the plain fallback
for unknown languages and code over 100 kB, and the tracking categories. (SyntaxHighlight 1.39.0 has no ``copy``
attribute; it came later.)

Parser interface: set_hook, get_strip_state, get_output, add_tracking_category, marker_index, config.
"""
